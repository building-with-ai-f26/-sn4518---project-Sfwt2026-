/*
 * Builds prototype/exercises.js (the FlexWeek exercise catalog) from:
 *   - data/exercises.json        the full free-exercise-db (public domain), 876 exercises
 *   - scripts/catalog-picks.txt  our curated picks, with our own equipment lists and fixes
 *
 * Run from the repo root:  node scripts/build-catalog.js
 *
 * If data/exercises.json is missing, download it first:
 *   curl -L -o data/exercises.json https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const db = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'exercises.json'), 'utf8'));
const byName = new Map(db.map((e) => [e.name.toLowerCase(), e]));

// The db has no instructions for these, so we wrote our own.
const OWN_INSTRUCTIONS = {
  'Side Bridge': [
    'Lie on your side with your legs straight and stacked, propped up on your forearm with the elbow directly under your shoulder.',
    'Lift your hips until your body forms a straight line from head to heels.',
    'Hold the position without letting your hips sag, then switch sides.',
  ],
};

const CATEGORY = { strength: 'strength', powerlifting: 'strength', stretching: 'stretch', cardio: 'cardio' };
const FIXABLE = { force: ['push', 'pull', 'static'], mechanic: ['compound', 'isolation'] };

const problems = [];
const catalog = [];

fs.readFileSync(path.join(__dirname, 'catalog-picks.txt'), 'utf8').split(/\r?\n/).forEach((raw, i) => {
  const row = raw.trim();
  if (!row || row.startsWith('#')) return;
  const [source, equip, display, fixes] = row.split('|').map((s) => s.trim());
  const e = byName.get(source.toLowerCase());
  if (!e) return problems.push('line ' + (i + 1) + ': "' + source + '" is not in the db');
  if (!equip) return problems.push('line ' + (i + 1) + ': "' + source + '" has no equipment column (use - for none)');

  const entry = {
    id: e.id,
    name: display || e.name,
    sourceName: e.name,
    category: CATEGORY[e.category],
    primaryMuscles: e.primaryMuscles || [],
    secondaryMuscles: e.secondaryMuscles || [],
    force: e.force || null, // 'push' | 'pull' | 'static' | null (cardio)
    mechanic: e.mechanic || null, // 'compound' | 'isolation' | null (most stretches, cardio)
    equipment: equip === '-' ? [] : equip.split(',').map((s) => s.trim()).filter(Boolean).sort(),
    instructions: OWN_INSTRUCTIONS[e.name] || e.instructions || [],
    gif: '', // placeholder for a later build
  };
  (fixes || '').split(',').map((s) => s.trim()).filter(Boolean).forEach((fix) => {
    const [field, value] = fix.split('=').map((s) => s.trim());
    if (!FIXABLE[field] || !FIXABLE[field].includes(value)) return problems.push('line ' + (i + 1) + ': bad fix "' + fix + '"');
    entry[field] = value;
  });

  if (!entry.category) problems.push(source + ': unexpected db category "' + e.category + '"');
  if (!entry.primaryMuscles.length) problems.push(source + ': no primary muscle');
  if (!entry.instructions.length) problems.push(source + ': no instructions');
  if (catalog.some((x) => x.id === entry.id)) problems.push(source + ': listed twice');
  catalog.push(entry);
});

if (problems.length) {
  console.error('Catalog NOT built:\n  ' + problems.join('\n  '));
  process.exit(1);
}

// The file we write. The data is generated; the small amount of logic below it is the alternatives rule.
const out = `/*
 * FlexWeek exercise catalog.
 * GENERATED by scripts/build-catalog.js from scripts/catalog-picks.txt — do not edit by hand.
 * Exercise data: free-exercise-db (public domain), https://github.com/yuhonas/free-exercise-db
 *
 * Works in the browser (window.FlexWeekCatalog) and in Node (require) for tests.
 */
(function (root) {
  'use strict';

  const EXERCISES = ${JSON.stringify(catalog, null, 1)};

  const BY_ID = {};
  EXERCISES.forEach((e) => { BY_ID[e.id] = e; });

  // Every physical thing any exercise needs, e.g. 'dumbbells', 'leg press machine'.
  const EQUIPMENT_ITEMS = Array.from(new Set(EXERCISES.flatMap((e) => e.equipment))).sort();

  const sameEquipment = (a, b) => a.equipment.join('|') === b.equipment.join('|');

  // Can this exercise be done with only the listed equipment? Bodyweight exercises always can.
  function canDo(exercise, available) {
    return exercise.equipment.every((item) => available.includes(item));
  }

  /**
   * Alternatives for an exercise, by rule:
   *   same primary muscle, same push/pull, same compound/isolation.
   * Equipment does not decide what counts as an alternative. It is only a filter:
   * pass the equipment the user has (a list of EQUIPMENT_ITEMS) to keep only the
   * alternatives they can actually do.
   * Order: alternatives that use different equipment come first (handy when a machine is taken).
   */
  function alternatives(id, available) {
    const e = BY_ID[id];
    if (!e) return [];
    const matches = EXERCISES.filter((x) =>
      x.id !== e.id &&
      x.primaryMuscles[0] === e.primaryMuscles[0] &&
      x.force === e.force &&
      x.mechanic === e.mechanic &&
      (!available || canDo(x, available)));
    return matches.filter((x) => !sameEquipment(x, e)).concat(matches.filter((x) => sameEquipment(x, e)));
  }

  const api = { EXERCISES, BY_ID, EQUIPMENT_ITEMS, canDo, alternatives };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.FlexWeekCatalog = api;
})(this);
`;

fs.writeFileSync(path.join(ROOT, 'prototype', 'exercises.js'), out);

// Summary, so a human can sanity-check the result without opening the big file.
const { alternatives, EQUIPMENT_ITEMS } = require(path.join(ROOT, 'prototype', 'exercises.js'));
const count = (cat) => catalog.filter((e) => e.category === cat).length;
console.log('Wrote prototype/exercises.js: ' + catalog.length + ' exercises (' +
  count('strength') + ' strength, ' + count('stretch') + ' stretch, ' + count('cardio') + ' cardio)');
console.log('\nEquipment items (' + EQUIPMENT_ITEMS.length + '): ' + EQUIPMENT_ITEMS.join(', '));
const alone = catalog.filter((e) => e.category === 'strength' && !alternatives(e.id).length).map((e) => e.name);
console.log('\nStrength exercises with no alternative (' + alone.length + '): ' + alone.join(', '));
